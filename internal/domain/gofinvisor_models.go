// Calculate methods for FinancialProfile
func (fp *FinancialProfile) GetInvestmentBudget() float64 {
	if fp.UseRatio {
		surplus := fp.MonthlyIncome - fp.FixedExpenses
		if surplus <= 0 {
			return 0
		}
		return surplus * fp.InvestmentRatio
	}
	return fp.InvestmentAmount
}

func (fp *FinancialProfile) GetDisposableIncome() float64 {
	return fp.MonthlyIncome - fp.FixedExpenses
}

// Calculate methods for Holding
func (h *Holding) UpdatePnL() {
	h.TotalValue = h.Quantity * h.CurrentPrice
	h.PnL = h.TotalValue - (h.Quantity * h.AvgBuyPrice)
	if h.AvgBuyPrice > 0 {
		h.PnLPercent = (h.PnL / (h.Quantity * h.AvgBuyPrice)) * 100
	}
}
