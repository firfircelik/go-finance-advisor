package domain

import (
	"time"

	"gorm.io/gorm"
)

// FinancialProfile represents user's financial information
type FinancialProfile struct {
	ID                uint    `gorm:"primaryKey"`
	UserID            uint    `gorm:"uniqueIndex;not null"`
	MonthlyIncome     float64 `gorm:"not null;default:0"`
	FixedExpenses     float64 `gorm:"not null;default:0"`
	InvestmentRatio   float64 `gorm:"not null;default:0.1"` // 10% default
	InvestmentAmount  float64 `gorm:"not null;default:0"`   // Fixed amount (alternative to ratio)
	UseRatio          bool    `gorm:"not null;default:true"` // Use ratio or fixed amount
	RiskTolerance     string  `gorm:"type:varchar(20);not null;default:'moderate'"`
	InvestmentGoals   string  `gorm:"type:text"`
	TimeHorizon       string  `gorm:"type:varchar(20)"` // short, medium, long
	CreatedAt         time.Time
	UpdatedAt         time.Time
	DeletedAt         gorm.DeletedAt `gorm:"index"`
}

// Portfolio represents user's investment portfolio
type Portfolio struct {
	ID        uint      `gorm:"primaryKey"`
	UserID    uint      `gorm:"not null"`
	Name      string    `gorm:"type:varchar(100);not null"`
	Holdings  []Holding `gorm:"foreignKey:PortfolioID"`
	TotalValue float64  `gorm:"not null;default:0"`
	CreatedAt time.Time
	UpdatedAt time.Time
}

// Holding represents a single asset holding in portfolio
type Holding struct {
	ID          uint    `gorm:"primaryKey"`
	PortfolioID uint    `gorm:"not null;index"`
	AssetType   string  `gorm:"type:varchar(20);not null"` // crypto, stock, forex
	Symbol      string  `gorm:"type:varchar(20);not null;index"`
	Quantity    float64 `gorm:"not null"`
	AvgBuyPrice float64 `gorm:"not null"`
	CurrentPrice float64 `gorm:"not null;default:0"`
	TotalValue  float64 `gorm:"not null;default:0"`
	PnL         float64 `gorm:"not null;default:0"`
	PnLPercent  float64 `gorm:"not null;default:0"`
	CreatedAt   time.Time
	UpdatedAt   time.Time
}

// MarketData represents time-series price data
